#!/usr/bin/env node
// Build the door reader (engine/door-reader, Rust) to WebAssembly and write
// the two committed artifacts the app and the MCP load:
//   web/src/lib/doorReader.wasm      the module
//   web/src/lib/doorReaderWasm.ts    the same bytes as base64 (no loader differences between Vite and Node)
// and engine/door-reader/BUILD.json (toolchain + sha256).
//
//   node scripts/build-door-reader.mjs           rebuild and write
//   node scripts/build-door-reader.mjs --check   rebuild in a temp target dir and fail unless the committed bytes match
//   node scripts/build-door-reader.mjs --check-embedded   no Rust needed: the .ts embeds exactly the committed .wasm
//
// Needs rustup's stable toolchain with the wasm32-unknown-unknown target.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const crate = path.join(root, "engine", "door-reader");
const wasmOut = path.join(root, "web", "src", "lib", "doorReader.wasm");
const tsOut = path.join(root, "web", "src", "lib", "doorReaderWasm.ts");
const stamp = path.join(crate, "BUILD.json");
const mode = process.argv[2] || "";

const sha = (b) => createHash("sha256").update(b).digest("hex");

function tsFor(bytes) {
  const b64 = Buffer.from(bytes).toString("base64");
  const lines = b64.match(/.{1,120}/g) || [];
  return `// GENERATED by scripts/build-door-reader.mjs from engine/door-reader. Do not edit.\n` +
    `// sha256 ${sha(bytes)}, ${bytes.length} bytes.\n` +
    `export const DOOR_READER_WASM_BASE64 =\n` + lines.map((l) => `  "${l}"`).join(" +\n") + ";\n";
}

function build(targetDir) {
  const env = {
    ...process.env,
    CARGO_TARGET_DIR: targetDir,
    // no machine paths in the module: identical bytes on any machine with the same toolchain
    RUSTFLAGS: `--remap-path-prefix=${crate}=door-reader --remap-path-prefix=${process.env.HOME || "/home"}=~`,
  };
  execFileSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "--locked"], { cwd: crate, env, stdio: "inherit" });
  return readFileSync(path.join(targetDir, "wasm32-unknown-unknown", "release", "door_reader.wasm"));
}

function toolchain() {
  try { return execFileSync("rustc", ["--version"], { encoding: "utf8" }).trim(); } catch { return "unknown"; }
}

if (mode === "--check-embedded") {
  const wasm = readFileSync(wasmOut);
  const ts = readFileSync(tsOut, "utf8");
  if (ts !== tsFor(wasm)) { console.error("doorReaderWasm.ts does not embed web/src/lib/doorReader.wasm: run node scripts/build-door-reader.mjs"); process.exit(1); }
  const want = JSON.parse(readFileSync(stamp, "utf8")).sha256;
  if (want !== sha(wasm)) { console.error(`doorReader.wasm sha256 ${sha(wasm)} != BUILD.json ${want}`); process.exit(1); }
  console.log(`door reader: embedded module matches (${sha(wasm).slice(0, 12)})`);
} else if (mode === "--check") {
  const tmp = mkdtempSync(path.join(tmpdir(), "door-reader-"));
  try {
    const fresh = build(tmp);
    const committed = readFileSync(wasmOut);
    if (sha(fresh) !== sha(committed)) {
      console.error(`door reader: source builds to ${sha(fresh)}, committed module is ${sha(committed)} (${toolchain()}; BUILD.json names the toolchain it was built with)`);
      process.exit(1);
    }
    console.log(`door reader: source matches the committed module (${sha(fresh).slice(0, 12)})`);
  } finally { rmSync(tmp, { recursive: true, force: true }); }
} else {
  const bytes = build(path.join(crate, "target"));
  writeFileSync(wasmOut, bytes);
  writeFileSync(tsOut, tsFor(bytes));
  writeFileSync(stamp, JSON.stringify({ toolchain: toolchain(), target: "wasm32-unknown-unknown", sha256: sha(bytes), bytes: bytes.length }, null, 2) + "\n");
  console.log(`door reader: ${bytes.length} bytes, sha256 ${sha(bytes)}`);
}
